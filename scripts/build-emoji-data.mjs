/**
 * Builds the emoji panel's data, one file per interface language, from
 * emojibase-data (MIT, https://emojibase.dev):
 *
 *   node scripts/build-emoji-data.mjs     writes src/features/emoji/data/<locale>.js
 *
 * Run it by hand when moving to a newer emojibase release: the files are
 * committed, the package depends on nothing at run time.
 *
 * Kept: every emoji of Unicode Emoji 14.0 or older, without skin tones or
 * components. Newer ones still show as an empty box on many phones and
 * desktop mail clients, and an email cannot choose its reader's fonts.
 * Each one carries its name and up to six keywords in the language, for the
 * search.
 */

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const OUT = path.join(root, 'src', 'features', 'emoji', 'data');
const VERSION = '18.0.0';
const MAX_EMOJI_VERSION = 14;
const MAX_KEYWORDS = 6;
const LOCALES = ['en', 'fr', 'de', 'es', 'pt', 'ru', 'zh'];

/** emojibase's groups, in its order (2, the components, is left out). */
const GROUPS = { 0: 'smileys', 1: 'people', 3: 'nature', 4: 'food', 5: 'travel', 6: 'activities', 7: 'objects', 8: 'symbols', 9: 'flags' };

async function fetchJson(file) {
  const url = `https://cdn.jsdelivr.net/npm/emojibase-data@${VERSION}/${file}`;
  const response = await fetch(url);
  if (!response.ok) throw new Error(`${url}: HTTP ${response.status}`);
  return response.json();
}

/** The name, then the keywords it does not already say. */
function searchText(entry) {
  const label = entry.label.toLowerCase();
  const tags = (entry.tags || []).map((tag) => tag.toLowerCase()).filter((tag) => !label.includes(tag));
  return [label, ...[...new Set(tags)].slice(0, MAX_KEYWORDS)].join('|');
}

const versions = new Map((await fetchJson('en/data.json')).map((entry) => [entry.hexcode, entry.version]));
fs.mkdirSync(OUT, { recursive: true });

for (const locale of LOCALES) {
  const entries = (await fetchJson(`${locale}/compact.json`))
    .filter((entry) => entry.group in GROUPS && (versions.get(entry.hexcode) ?? Infinity) <= MAX_EMOJI_VERSION)
    .sort((a, b) => a.order - b.order);
  const groups = Object.values(GROUPS).map((id) => ({ id, emojis: [] }));
  for (const entry of entries) {
    groups.find((group) => group.id === GROUPS[entry.group]).emojis.push([entry.unicode, searchText(entry)]);
  }
  const body = groups
    .map(({ id, emojis }) => `  [${JSON.stringify(id)}, [\n${emojis.map((row) => `    ${JSON.stringify(row)},`).join('\n')}\n  ]],`)
    .join('\n');
  const source =
    // A legal comment: the bundler keeps it in the chunk.
    `/*! Emoji names and keywords: emojibase-data ${VERSION}, MIT License, Copyright (c) 2017-2019 Miles Johnson. See THIRD-PARTY-NOTICES.md. */\n` +
    `// Generated by scripts/build-emoji-data.mjs. Do not edit.\n` +
    `// [group, [[emoji, "name|keyword|…"], …]], in Unicode order.\n` +
    `export default [\n${body}\n];\n`;
  fs.writeFileSync(path.join(OUT, `${locale}.js`), source);
  console.log(`${locale}: ${entries.length} emojis, ${Math.round(Buffer.byteLength(source) / 1024)} KB`);
}
